// ─── emit-image-migration.mjs ────────────────────────────────────────────────
// Writes supabase/migrations/0021_product_photography.sql from the catalogue.
//
//   node --import tsx scripts/photography/emit-image-migration.mjs
//
// WHY 0014 IS NOT ENOUGH. The regenerated seed carries all 140 products, but
// every statement in it is `on conflict do nothing` — deliberately, so that
// re-seeding can never clobber a row the admin has since edited. That is
// exactly right for the 57 NEW products (they insert, images and all), and
// exactly wrong for the 83 that already exist: their rows are already there,
// so the insert is skipped and their `images` column keeps the empty URLs it
// was seeded with in April.
//
// So the photographs need a targeted UPDATE, which is this file.
//
// IT STILL WILL NOT CLOBBER AN ADMIN UPLOAD. The update is guarded: it only
// touches rows whose images are absent or carry an empty `url`. If someone has
// uploaded a real photograph through /admin between this being written and
// being applied, that row is left alone — their upload is fresher than this
// migration, and a migration should never overwrite a human's later decision.

import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { HARDCODED_CATALOGUE } from '../../packages/shared/src/catalogue/products.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'supabase', 'migrations', '0021_product_photography.sql');

/** Single-quote escaping for a SQL string literal. */
const sql = (s) => `'${String(s).replace(/'/g, "''")}'`;

const withPhotos = HARDCODED_CATALOGUE.filter((p) => p.images.some((i) => i.url));

const rows = withPhotos
  .map((p) => {
    const images = p.images.filter((i) => i.url);
    return `    (${sql(p.slug)}, ${sql(JSON.stringify(images))}::jsonb)`;
  })
  .join(',\n');

const out = `-- ─── 0021 · Product photography — GENERATED, do not edit by hand ──────────
-- Generated by: node --import tsx scripts/photography/emit-image-migration.mjs
-- Source: packages/shared/src/catalogue/products.ts (HARDCODED_CATALOGUE)
--
-- The Khammam photography drop of 2026-08-13 and the namkeen drop of
-- 2026-08-23, applied to rows that already exist. 0014_seed_products.sql
-- inserts any product the database is missing with its images attached, but
-- it is \`on conflict do nothing\`, so it cannot fill in the images of a product
-- that was seeded back in April. This does.
--
-- GUARDED: only rows with no usable image are touched, so an admin upload made
-- after this migration was written survives it. Re-running is therefore safe
-- and idempotent — the second run matches nothing.
--
-- ${withPhotos.length} products carry a photograph. The rest keep the placeholder on
-- purpose: the drop contained no pickle jar, no podi and no loose nuts. See
-- STILL_UNSHOT in scripts/photography/shot-list.mjs for the next shoot's brief.
begin;

update public.products as p
set images = v.images
from (values
${rows}
) as v(slug, images)
where p.slug = v.slug
  and not exists (
    select 1
    from jsonb_array_elements(coalesce(p.images, '[]'::jsonb)) as img
    where coalesce(img ->> 'url', '') <> ''
  );

commit;
`;

writeFileSync(OUT, out, 'utf8');
console.log(
  `[photography] Wrote ${path.relative(ROOT, OUT)} — ${withPhotos.length} products with photographs.`,
);
