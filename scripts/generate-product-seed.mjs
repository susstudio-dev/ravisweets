// ─── generate-product-seed.mjs ──────────────────────────────────────────────
// Emits supabase/migrations/0014_seed_products.sql from the shared CATALOGUE.
//
// Run from the repo root:   pnpm run generate:seed
// (wired as `node --import tsx scripts/generate-product-seed.mjs` — tsx lets
// this .mjs import the TypeScript catalogue module directly.)
//
// Deterministic on purpose: products are sorted by id, variants keep their
// catalogue order, and no timestamps are embedded — re-running the generator
// is byte-identical, so a catalogue change shows up as a reviewable diff.
//
// Every insert is an untargeted `on conflict do nothing`: the seed must NEVER
// clobber rows the admin has since edited. Re-applying the file only fills
// gaps. Untargeted deliberately — `on conflict (id)` guards only the primary
// key, so a row whose SKU already exists under a different id raised 23505 and
// aborted the whole transaction instead of being skipped.

import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// HARDCODED_CATALOGUE, not CATALOGUE. Since the build-time bake landed,
// CATALOGUE resolves to the *database* contents (products.generated.ts) when
// there are any, so seeding from it would round-trip the database back into a
// migration and make this file's output depend on the network. The seed's job
// is unchanged: publish the hand-authored array as the starting state for an
// empty database.
import { HARDCODED_CATALOGUE as CATALOGUE } from '../packages/shared/src/catalogue/products.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = path.join(ROOT, 'supabase', 'migrations', '0014_seed_products.sql');

/** Escape a text value for a single-quoted SQL literal (single quotes doubled). */
function sqlText(value) {
  if (value === undefined || value === null) return 'null';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlNumber(value) {
  if (value === undefined || value === null) return 'null';
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`Non-finite number in catalogue data: ${value}`);
  }
  return String(value);
}

function sqlBool(value) {
  return value ? 'true' : 'false';
}

/** text[] literal: array['a','b'] — empty arrays as '{}'. */
function sqlTextArray(values) {
  if (!values || values.length === 0) return "'{}'";
  return `array[${values.map((v) => sqlText(v)).join(', ')}]`;
}

/**
 * jsonb literal via dollar-quoting so JSON's own quotes need no escaping.
 * The tag is chosen so it can never collide with the payload: if the JSON
 * happens to contain `$json$` we fall back to `$rsjson$`, `$rsjson1$`, … —
 * the loop always terminates because the payload is finite.
 */
function sqlJsonb(value) {
  if (value === undefined || value === null) return 'null';
  const json = JSON.stringify(value);
  let tag = '$json$';
  for (let i = 0; json.includes(tag); i += 1) {
    tag = i === 0 ? '$rsjson$' : `$rsjson${i}$`;
  }
  return `${tag}${json}${tag}::jsonb`;
}

/** date literal — the catalogue stores plain ISO dates (YYYY-MM-DD). */
function sqlDate(value) {
  if (value === undefined || value === null) return 'null';
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) {
    throw new Error(`rubric_passed_on is not a plain ISO date: ${value}`);
  }
  return `date '${value}'`;
}

const products = [...CATALOGUE].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
const variantCount = products.reduce((n, p) => n + p.variants.length, 0);

const lines = [];
lines.push('-- ─── 0014 · Product + variant seed — GENERATED, do not edit by hand ───────');
lines.push('-- Generated by: pnpm run generate:seed  (scripts/generate-product-seed.mjs)');
lines.push('-- Source: packages/shared/src/catalogue/products.ts (CATALOGUE)');
lines.push(`-- Contents: ${products.length} products · ${variantCount} variants (SKUs)`);
lines.push('--');
lines.push('-- Every insert is an UNTARGETED `on conflict do nothing`, so it covers the');
lines.push('-- unique on variants.sku as well as the primary key. Targeting `(id)` made');
lines.push('-- this file abort with 23505 whenever a SKU already existed under a');
lines.push('-- different id. Seeding must never clobber');
lines.push('-- a row the admin has since edited from /admin — re-applying this file only');
lines.push('-- fills whatever is missing. To push a catalogue change into an existing row,');
lines.push('-- edit it in the admin (or write a targeted update), never via this seed.');
lines.push('begin;');

const PRODUCT_COLUMNS =
  'id, slug, title, description, category, subcategory, dietary_tags, ingredients, ' +
  'allergens, storage_instructions, shelf_life_days, images, region_availability, ' +
  'featured, bestseller, is_new, theme_palette, garnish, builder_eligible, ' +
  'rubric_passed_on, source_url, unit_mode';

const VARIANT_COLUMNS =
  'id, product_id, title, weight_grams, price_amount, price_currency, sku, stock_available';

for (const product of products) {
  const values = [
    sqlText(product.id),
    sqlText(product.slug),
    sqlText(product.title),
    sqlText(product.description),
    sqlText(product.category),
    sqlText(product.subcategory ?? null),
    sqlTextArray(product.dietary_tags),
    sqlTextArray(product.ingredients),
    sqlTextArray(product.allergens),
    sqlText(product.storage_instructions ?? null),
    sqlNumber(product.shelf_life_days ?? null),
    sqlJsonb(product.images),
    sqlTextArray(product.region_availability),
    sqlBool(product.featured),
    sqlBool(product.bestseller),
    sqlBool(product.new), // products.is_new ← Product.new
    sqlJsonb(product.theme_palette ?? null),
    sqlText(product.garnish ?? null),
    sqlBool(product.builder_eligible),
    sqlDate(product.rubric_passed_on),
    sqlText(product.source_url ?? null),
    // unit_mode is `not null default 'weight'` (0002) — an explicit null would
    // violate the constraint, so absent means "let the column default apply".
    product.unit_mode ? sqlText(product.unit_mode) : 'default',
  ];
  lines.push('');
  lines.push(
    `-- ${product.title} (${product.variants.length} variant${product.variants.length === 1 ? '' : 's'})`,
  );
  lines.push(`insert into public.products (${PRODUCT_COLUMNS})`);
  lines.push(`values (${values.join(', ')})`);
  lines.push('on conflict do nothing;');
  for (const variant of product.variants) {
    const variantValues = [
      sqlText(variant.id),
      sqlText(product.id),
      sqlText(variant.title),
      sqlNumber(variant.weight_grams),
      sqlNumber(variant.price.amount), // verbatim — same unit as Money.amount
      sqlText(variant.price.currency),
      sqlText(variant.sku),
      sqlNumber(variant.stock_available),
    ];
    lines.push(`insert into public.variants (${VARIANT_COLUMNS})`);
    lines.push(`values (${variantValues.join(', ')})`);
    lines.push('on conflict do nothing;');
  }
}

lines.push('');
lines.push('commit;');

writeFileSync(OUT_FILE, `${lines.join('\n')}\n`, 'utf8');
console.log(
  `Wrote ${path.relative(ROOT, OUT_FILE)} — ${products.length} products, ${variantCount} variants.`,
);
